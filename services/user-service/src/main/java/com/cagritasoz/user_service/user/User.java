package com.cagritasoz.user_service.user;

import jakarta.persistence.*;
import lombok.*;
import org.hibernate.annotations.Generated;
import org.hibernate.generator.EventType;

import java.time.Instant;
import java.util.UUID;

@Entity
@Table(name = "users")
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class User {

    @Id
    private UUID id;

    @Column(nullable = false)
    private String email;

    @Column(name = "display_name", nullable = false)
    private String displayName;

    @Builder.Default
    @Column(nullable = false)
    private String timezone = "UTC";

    @Builder.Default
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private UserStatus status = UserStatus.ACTIVE;

    @Version
    @Column(nullable = false)
    private Long version;

    // The deletion timestamps (V5, V9, V11): requested = the user asked, scheduled_for = when the grace period
    // ends, started_at = when the cleanup began, deleted_at = when it finished. The database ties each one to the
    // statuses that imply it.
    @Column(name = "deletion_requested_at")
    private Instant deletionRequestedAt;

    @Column(name = "deletion_scheduled_for")
    private Instant deletionScheduledFor;

    @Column(name = "deletion_started_at")
    private Instant deletionStartedAt;

    @Column(name = "deleted_at")
    private Instant deletedAt;

    // Set once the Keycloak user is hard-deleted, which happens while the row is DELETING (V9, V12).
    @Column(name = "keycloak_deleted_at")
    private Instant keycloakDeletedAt;

    // @Generated -> "This column is generated by the database."
    // Hibernate retrieves the database-generated value after insertion and updates the in memory managed entity.
    // "insertable = false": Do not include created_at in SQL INSERT statements that Hibernate generates.
    // "updatable = false": Do not include this column in Hibernate-generated UPDATE statements.
    // JdbcTemplate can bypass these directly and can insert or update these columns directly.
    @Generated(event = EventType.INSERT)
    @Column(name = "created_at", nullable = false, insertable = false, updatable = false)
    private Instant createdAt;

    // See migration V6 for trigger.
    // Hibernate retrieves the database-generated value after insertion or update.
    @Generated(event = {EventType.INSERT, EventType.UPDATE})
    @Column(name = "updated_at", nullable = false, insertable = false, updatable = false)
    private Instant updatedAt;
}